def replace_in_file(filepath):
    """Replace emoji icons with inline SVGs in a Vue file."""
    with open(filepath, 'r') as f:
        content = f.read()
    
    original = content
    changes = []
    
    for emoji, (svg_name, size) in REPLACEMENTS.items():
        svg = emoji_to_svg(svg_name, size)
        if not svg:
            continue
        
        # Count occurrences before replacement
        count = content.count(emoji)
        if count == 0:
            continue
        
        # Replace emoji with SVG + space (preserve readability)
        new_content = content.replace(emoji, svg + ' ')
        if new_content != content:
            changes.append((emoji, svg_name, count))
            content = new_content
    
    if changes:
        with open(filepath, 'w') as f:
            f.write(content)
        for emoji, svg_name, count in changes:
            print(f"  {emoji} → {svg_name} ({count}x)")
        return True
    return False

